"""Build inference fixtures; expected language symbols are independent of the resolver."""
import json
import pathlib
import subprocess
import xml.etree.ElementTree as ET

root = pathlib.Path('/src')
out = pathlib.Path('/out')
proto_root = root / 'tests/naming/proto'
cases = []
for name, go_name in [('snake_case', 'SnakeCase'), ('foo__bar', 'Foo_Bar'),
                      ('_leading', 'XLeading'), ('HTTP_service2API', 'HTTPService2API'),
                      ('foo2_bar', 'Foo2Bar'), ('_', 'X'), ('package', 'Package')]:
    cases.append(dict(file='nested-dir/name-edge.proto', service='unusual_proto.v2alpha.' + name,
                      name=name, go_name=go_name, go_pkg='edge', java='com.example.generated',
                      cs='Explicit.Namespace', py='nested_dir.name_edge_pb2_grpc'))
cases += [dict(file='fallback.proto', service='some_api.v2alpha.HTTP_api.FallbackService',
               name='FallbackService', go_name='FallbackService', go_pkg='fallback',
               java='some_api.v2alpha.HTTP_api', cs='SomeApi.V2Alpha.HTTPApi', py='fallback_pb2_grpc'),
          dict(file='global.proto', service='GlobalService', name='GlobalService',
               go_name='GlobalService', go_pkg='globalcase', java='com.example.globalcase',
               cs='', py='global_pb2_grpc'),
          dict(file='keyword.proto', service='keyword_case.class', name='class', go_name='Class',
               go_pkg='keywordcase', java='com.example.keywordcase', cs=None, py='keyword_pb2_grpc')]

def run(*args):
    subprocess.run(args, check=True)

out.mkdir(exist_ok=True)
for i, case in enumerate(cases):
    run('/proto-contract', 'snapshot', '--proto', str(proto_root / case['file']),
        '--proto-path', str(proto_root), '--service', case['service'], '--api', f'naming.{i}',
        '--version', '1.0.0', '--out', str(out / f'lock{i}.json'))

for language in ('go', 'python', 'java', 'dotnet'):
    folder = out / language
    folder.mkdir()
    bindings = []
    for i, case in enumerate(cases):
        if language in ('dotnet', 'python') and case['cs'] is None:
            # Both generators emit a bare keyword class and cannot compile it.
            continue
        output = {'go': f'contracts/c{i}/contract.go', 'python': f'c{i}.py',
                  'java': f'src/main/java/contracts/c{i}/Contract.java', 'dotnet': f'c{i}.cs'}[language]
        binding = dict(service=case['service'], lock=f'../lock{i}.json', output=output)
        if language == 'go': binding['package'] = f'c{i}'
        if language == 'java': binding['package'] = f'contracts.c{i}'
        if language == 'dotnet': binding.update(package=f'Contracts.C{i}', target='both')
        bindings.append(binding)
    config = folder / 'bindings.json'
    config.write_text(json.dumps(dict(bindings=bindings)))
    run('protoc', '-I' + str(proto_root), '--plugin=protoc-gen-proto-contract=/protoc-gen-proto-contract',
        '--proto-contract_out=' + str(folder),
        '--proto-contract_opt=lang=' + language + ',bindings=' + str(config),
        *sorted({case['file'] for case in cases if language not in ('dotnet', 'python') or case['cs'] is not None}))

# Actual Go bindings are generated by protoc-gen-go and protoc-gen-go-grpc.
go = out / 'go'
run('protoc', '-I' + str(proto_root), '--go_out=' + str(go), '--go_opt=module=example.test/naming',
    '--go-grpc_out=' + str(go), '--go-grpc_opt=module=example.test/naming',
    *sorted({case['file'] for case in cases}))
(go / 'go.mod').write_text('module example.test/naming\ngo 1.22.0\n'
                          'require github.com/dunkymole/proto-contract v0.0.0\n'
                          'replace github.com/dunkymole/proto-contract => /src\n')
imports = ['"testing"', '"github.com/dunkymole/proto-contract/runtimes/go/protocontract"']
imports += [f'c{i} "example.test/naming/contracts/c{i}"' for i in range(len(cases))]
for pkg in sorted({case['go_pkg'] for case in cases}):
    imports.append(f'{pkg} "example.test/naming/pb/{pkg}"')
body = ['b := protocontract.NewServerBuilder()']
for i, case in enumerate(cases):
    symbol = case['go_pkg'] + '.' + case['go_name']
    body += [f'var _ {symbol}Client = c{i}.NewClient(nil)',
             f'if err := c{i}.RegisterServer(b, &{case["go_pkg"]}.Unimplemented{case["go_name"]}Server{{}}); err != nil {{ t.Fatal(err) }}']
body += ['s, err := b.Build(); if err != nil { t.Fatal(err) }; s.Stop()']
(go / 'naming_test.go').write_text('package naming_test\nimport (\n' + '\n'.join(imports) +
                                  '\n)\nfunc TestActualGeneratorSymbols(t *testing.T) {\n' + '\n'.join(body) + '\n}\n')

# Python exercises the actual import paths, concrete stub types and service registrations.
py_lines = ['import importlib, grpc', 'from concurrent import futures', 'from proto_contract import ServerBuilder',
            'builder = ServerBuilder()', 'with grpc.insecure_channel("localhost:1") as channel:']
for i, case in enumerate(cases):
    if case['cs'] is None: continue
    py_lines += [f'    contract = importlib.import_module("c{i}")',
                 f'    pb = importlib.import_module("{case["py"]}")',
                 f'    assert isinstance(contract.client(channel), pb.{case["name"]}Stub)',
                 f'    contract.add_to_server(builder, pb.{case["name"]}Servicer())']
py_lines += ['server = builder.build(futures.ThreadPoolExecutor(max_workers=1))', 'server.stop(0)',
             'print("PASS Python actual generator naming/imports")']
(out / 'python/check.py').write_text('\n'.join(py_lines) + '\n')

# Java compiles all three stub variants and typed server registrations.
java = out / 'java'
java_lines = ['package naming;', 'public class Check {', 'public static void main(String[] args) {',
              'var channel = io.grpc.ManagedChannelBuilder.forTarget("localhost:1").usePlaintext().build();',
              'var builder = new io.github.dunkymole.protocontract.ContractServerBuilder(io.grpc.ServerBuilder.forPort(0));']
for i, case in enumerate(cases):
    symbol = case['java'] + '.' + case['name'] + 'Grpc'
    java_lines += [f'{symbol}.{case["name"]}Stub async{i} = contracts.c{i}.Contract.client(channel);',
                   f'{symbol}.{case["name"]}BlockingStub blocking{i} = contracts.c{i}.Contract.blockingClient(channel);',
                   f'{symbol}.{case["name"]}FutureStub future{i} = contracts.c{i}.Contract.futureClient(channel);',
                   f'contracts.c{i}.Contract.addService(builder, new {symbol}.{case["name"]}ImplBase() {{}});']
java_lines += ['builder.build().shutdownNow();', 'channel.shutdownNow();',
              'System.out.println("PASS Java actual generator naming");', '}', '}']
(java / 'src/main/java/naming').mkdir(parents=True)
(java / 'src/main/java/naming/Check.java').write_text('\n'.join(java_lines))
pom = (root / 'examples/clients/java/pom.xml').read_text()
pom = pom.replace('io.github.dunkymole.protocontract.demo.Client', 'naming.Check')
(java / 'pom.xml').write_text(pom)

# .NET checks explicit, fallback and global namespaces using real Grpc.Tools output.
cs_lines = ['using ProtoContract;', 'using Microsoft.AspNetCore.Routing;',
            'var builder = WebApplication.CreateBuilder();', 'builder.Services.AddContractGrpc();',
            'await using var app = builder.Build();',
            'using var channel = Grpc.Net.Client.GrpcChannel.ForAddress("http://localhost:1");']
classes = []
for i, case in enumerate(cases):
    if case['cs'] is None: continue
    symbol = 'global::' + (case['cs'] + '.' if case['cs'] else '') + case['name']
    cs_lines += [f'{symbol}.{case["name"]}Client client{i} = Contracts.C{i}.Contract.CreateClient(channel);',
                 f'Contracts.C{i}.Contract.MapService<Impl{i}>(app);']
    classes.append(f'sealed class Impl{i} : {symbol}.{case["name"]}Base {{}}')
cs_lines += ['_ = ((IEndpointRouteBuilder)app).DataSources.SelectMany(s => s.Endpoints).ToArray();',
             'Console.WriteLine("PASS .NET actual generator naming/namespaces");'] + classes
(out / 'dotnet/Program.cs').write_text('\n'.join(cs_lines))
(out / 'dotnet/Check.csproj').write_text('''<Project Sdk="Microsoft.NET.Sdk.Web">
<PropertyGroup><TargetFramework>net9.0</TargetFramework><ImplicitUsings>enable</ImplicitUsings><Nullable>enable</Nullable></PropertyGroup>
<ItemGroup><ProjectReference Include="/src/runtimes/dotnet-aspnetcore/ProtoContract.AspNetCore.csproj" />
<PackageReference Include="Google.Protobuf" Version="3.30.2" /><PackageReference Include="Grpc.Net.Client" Version="2.71.0" />
<PackageReference Include="Grpc.Tools" Version="2.72.0" PrivateAssets="All" />
<Protobuf Include="proto/nested-dir/name-edge.proto;proto/fallback.proto;proto/global.proto" GrpcServices="Both" />
</ItemGroup></Project>''')
